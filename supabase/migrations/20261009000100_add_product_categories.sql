CREATE TABLE IF NOT EXISTS public.product_categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  label text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT product_categories_name_not_blank
    CHECK (length(btrim(name)) > 0),
  CONSTRAINT product_categories_label_not_blank
    CHECK (length(btrim(label)) > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS product_categories_name_normalized_key
  ON public.product_categories (lower(btrim(name)));

ALTER TABLE public.product_categories ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.product_categories FROM PUBLIC, anon, authenticated;
GRANT ALL ON public.product_categories TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.product_categories_id_seq TO service_role;

