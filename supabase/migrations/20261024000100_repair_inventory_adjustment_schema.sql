CREATE OR REPLACE FUNCTION public.adjust_product_inventory(
  p_product_id text,
  p_quantity_delta integer,
  p_reason text,
  p_note text DEFAULT NULL,
  p_actor text DEFAULT 'admin'
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
  v_product public.products%ROWTYPE;
  v_after integer;
  v_adjustment public.inventory_adjustments%ROWTYPE;
BEGIN
  IF p_product_id IS NULL OR btrim(p_product_id) = ''
     OR p_quantity_delta IS NULL
     OR p_quantity_delta = 0
     OR abs(p_quantity_delta::bigint) > 100000 THEN
    RAISE EXCEPTION '商品編號或庫存調整數量無效'
      USING ERRCODE = '22023';
  END IF;
  IF p_reason IS NULL OR p_reason NOT IN ('損毀', '員工自用', '實體盤點差異', '其他') THEN
    RAISE EXCEPTION '庫存調整原因無效'
      USING ERRCODE = '22023';
  END IF;
  IF p_note IS NOT NULL AND (
    length(p_note) > 500 OR p_note ~ '[[:cntrl:]]'
  ) THEN
    RAISE EXCEPTION '庫存調整備註格式無效'
      USING ERRCODE = '22023';
  END IF;

  SELECT *
    INTO v_product
  FROM public.products
  WHERE id::text = p_product_id
  FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION '找不到指定商品'
      USING ERRCODE = 'P0002';
  END IF;
  IF COALESCE(v_product.stock, 0) + p_quantity_delta < 0
     OR COALESCE(v_product.stock, 0) + p_quantity_delta > 2147483647 THEN
    RAISE EXCEPTION '調整後庫存不可小於零或超出可儲存範圍'
      USING ERRCODE = '22023';
  END IF;
  v_after := COALESCE(v_product.stock, 0) + p_quantity_delta;

  UPDATE public.products
  SET stock = v_after
  WHERE id::text = p_product_id;

  INSERT INTO public.inventory_adjustments (
    product_id,
    quantity_before,
    quantity_delta,
    quantity_after,
    reason,
    note,
    actor
  )
  VALUES (
    v_product.id,
    COALESCE(v_product.stock, 0),
    p_quantity_delta,
    v_after,
    p_reason,
    NULLIF(btrim(p_note), ''),
    COALESCE(NULLIF(btrim(p_actor), ''), 'admin')
  )
  RETURNING * INTO v_adjustment;

  RETURN jsonb_build_object(
    'adjustment_id', v_adjustment.adjustment_id,
    'product_id', v_product.id,
    'quantity_before', v_adjustment.quantity_before,
    'quantity_delta', v_adjustment.quantity_delta,
    'quantity_after', v_adjustment.quantity_after,
    'reason', v_adjustment.reason,
    'note', v_adjustment.note,
    'created_at', v_adjustment.created_at
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.adjust_product_inventory(text, integer, text, text, text)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.adjust_product_inventory(text, integer, text, text, text)
