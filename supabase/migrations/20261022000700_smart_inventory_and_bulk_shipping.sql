CREATE OR REPLACE FUNCTION public.get_product_inventory_alerts(
  p_safety_stock integer DEFAULT 3,
  p_target_stock integer DEFAULT 10,
  p_slow_days integer DEFAULT 30
)
RETURNS TABLE (
  product_id text,
  product_name text,
  stock integer,
  safety_stock integer,
  suggested_restock_quantity integer,
  last_order_date timestamptz,
  days_since_last_order integer,
  is_restock_needed boolean,
  is_slow_moving boolean
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
BEGIN
  IF p_safety_stock IS NULL OR p_safety_stock < 0 OR p_safety_stock > 100000
     OR p_target_stock IS NULL OR p_target_stock < 1 OR p_target_stock > 100000
     OR p_target_stock < p_safety_stock
     OR p_slow_days IS NULL OR p_slow_days < 1 OR p_slow_days > 3650 THEN
    RAISE EXCEPTION '庫存警示查詢參數無效'
      USING ERRCODE = '22023';
  END IF;

  RETURN QUERY
  WITH last_sales AS (
    SELECT oi.product_id, max(o.order_date) AS last_order_date
    FROM public.order_items AS oi
    JOIN public.orders AS o ON o.order_id = oi.order_id
    GROUP BY oi.product_id
  ),
  inventory AS (
    SELECT
      p.id::text AS product_id,
      COALESCE(p.product_name, p.name, '未命名商品')::text AS product_name,
      COALESCE(p.stock, 0)::integer AS stock,
      p.created_at,
      last_sales.last_order_date
    FROM public.products AS p
    LEFT JOIN last_sales ON last_sales.product_id = p.id
    WHERE COALESCE(p.status, '') <> '已下架'
  )
  SELECT
    inventory.product_id,
    inventory.product_name,
    inventory.stock,
    p_safety_stock,
    GREATEST(p_target_stock - inventory.stock, 0),
    inventory.last_order_date,
    CASE
      WHEN inventory.last_order_date IS NULL THEN
        GREATEST((CURRENT_DATE - inventory.created_at::date)::integer, 0)
      ELSE GREATEST((CURRENT_DATE - inventory.last_order_date::date)::integer, 0)
    END,
    inventory.stock <= p_safety_stock,
    CASE
      WHEN inventory.last_order_date IS NULL THEN
        inventory.created_at < now() - make_interval(days => p_slow_days)
      ELSE inventory.last_order_date < now() - make_interval(days => p_slow_days)
    END
  FROM inventory
  WHERE inventory.stock <= p_safety_stock
     OR CASE
       WHEN inventory.last_order_date IS NULL THEN
         inventory.created_at < now() - make_interval(days => p_slow_days)
       ELSE inventory.last_order_date < now() - make_interval(days => p_slow_days)
     END
  ORDER BY
    (inventory.stock <= p_safety_stock) DESC,
    CASE
      WHEN inventory.last_order_date IS NULL THEN inventory.created_at
      ELSE inventory.last_order_date
    END ASC,
    inventory.product_name;
END;
$function$;

REVOKE ALL ON FUNCTION public.get_product_inventory_alerts(integer, integer, integer)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.get_product_inventory_alerts(integer, integer, integer)
  TO service_role;

DROP FUNCTION IF EXISTS public.list_admin_customers(text, integer, integer);

CREATE FUNCTION public.list_admin_customers(
  p_search text DEFAULT NULL,
  p_limit integer DEFAULT 50,
  p_offset integer DEFAULT 0
)
RETURNS TABLE (
  id uuid,
  customer_phone text,
  customer_name text,
  credit_status text,
  default_shipping_method text,
  notes text,
  created_at timestamptz,
  total_orders bigint,
  total_spent numeric,
  tags text[]
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
  WITH customer_totals AS (
    SELECT
      c.id,
      c.customer_phone,
      c.customer_name,
      c.credit_status,
      c.default_shipping_method,
      c.notes,
      c.created_at,
      COUNT(DISTINCT o.order_id)::bigint AS total_orders,
      COALESCE(SUM(o.total_amount), 0)::numeric AS total_spent
    FROM public.customers AS c
    LEFT JOIN public.orders AS o ON o.customer_phone = c.customer_phone
    WHERE p_search IS NULL
       OR c.customer_phone ILIKE '%' || p_search || '%'
       OR COALESCE(c.customer_name, '') ILIKE '%' || p_search || '%'
    GROUP BY c.id
  ),
  customer_product_counts AS (
    SELECT
      customer.customer_phone,
      p.product_name,
      p.name,
      COALESCE(SUM(oi.quantity), 0) AS purchase_count
    FROM public.customers AS customer
    JOIN public.orders AS o ON o.customer_phone = customer.customer_phone
    JOIN public.order_items AS oi ON oi.order_id = o.order_id
    JOIN public.products AS p ON p.id = oi.product_id
    WHERE p_search IS NULL
       OR customer.customer_phone ILIKE '%' || p_search || '%'
       OR COALESCE(customer.customer_name, '') ILIKE '%' || p_search || '%'
    GROUP BY customer.customer_phone, p.product_name, p.name
  ),
  preferences AS (
    SELECT
      ranked.customer_phone,
      array_agg(
        '#喜歡' || left(COALESCE(ranked.product_name, ranked.name, '商品'), 20)
        ORDER BY ranked.purchase_count DESC, COALESCE(ranked.product_name, ranked.name)
      ) AS tags
    FROM (
      SELECT
        counts.*,
        row_number() OVER (
          PARTITION BY counts.customer_phone
          ORDER BY counts.purchase_count DESC, COALESCE(counts.product_name, counts.name)
        ) AS preference_rank
      FROM customer_product_counts AS counts
    ) AS ranked
    WHERE ranked.preference_rank <= 2
    GROUP BY ranked.customer_phone
  )
  SELECT
    totals.id,
    totals.customer_phone,
    totals.customer_name,
    totals.credit_status,
    totals.default_shipping_method,
    totals.notes,
    totals.created_at,
    totals.total_orders,
    totals.total_spent,
    array_remove(
      ARRAY[
        CASE WHEN totals.total_orders >= 5 THEN '#熟客VIP' END,
        CASE WHEN totals.total_spent >= 5000 THEN '#高消費客群' END
      ]::text[] || COALESCE(preferences.tags, ARRAY[]::text[]),
      NULL
    ) AS tags
  FROM customer_totals AS totals
  LEFT JOIN preferences ON preferences.customer_phone = totals.customer_phone
  ORDER BY totals.created_at DESC, totals.id
  LIMIT p_limit
  OFFSET p_offset;
$function$;

REVOKE ALL ON FUNCTION public.list_admin_customers(text, integer, integer)
  FROM PUBLIC, anon, authenticated;
