CREATE OR REPLACE FUNCTION public.bulk_ship_orders(p_shipments jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
  v_item jsonb;
  v_order_id text;
  v_order_ids text[] := ARRAY[]::text[];
  v_seen_order_numbers text[] := ARRAY[]::text[];
  v_result jsonb;
  v_results jsonb := '[]'::jsonb;
  v_order_number text;
  v_tracking_number text;
  v_shipping_method text;
BEGIN
  IF p_shipments IS NULL OR jsonb_typeof(p_shipments) <> 'array' THEN
    RAISE EXCEPTION '物流匯入必須是 JSON 陣列'
      USING ERRCODE = '22023';
  END IF;
  IF jsonb_array_length(p_shipments) NOT BETWEEN 1 AND 100 THEN
    RAISE EXCEPTION '物流匯入必須包含 1 至 100 筆資料'
      USING ERRCODE = '22023';
  END IF;

  FOR v_item IN SELECT value FROM jsonb_array_elements(p_shipments) LOOP
    v_order_number := upper(btrim(v_item->>'order_number'));
    v_tracking_number := btrim(v_item->>'tracking_number');
    v_shipping_method := btrim(v_item->>'shipping_method');
    IF v_order_number IS NULL OR v_order_number = ''
       OR length(v_order_number) > 100
       OR v_tracking_number IS NULL OR v_tracking_number = ''
       OR length(v_tracking_number) > 100
       OR v_shipping_method IS NULL
       OR v_shipping_method NOT IN ('面交', '自取', '順豐', '京東') THEN
      RAISE EXCEPTION '物流匯入包含無效訂單編號、運單號或運送方式'
        USING ERRCODE = '22023';
    END IF;
    IF v_order_number = ANY(v_seen_order_numbers) THEN
      RAISE EXCEPTION '物流匯入包含重複訂單編號 %', v_order_number
        USING ERRCODE = '22023';
    END IF;
    v_seen_order_numbers := array_append(v_seen_order_numbers, v_order_number);

    SELECT order_row.order_id::text
      INTO v_order_id
    FROM public.orders AS order_row
    WHERE upper(btrim(order_row.order_number)) = v_order_number
    FOR UPDATE;
    IF NOT FOUND THEN
      RAISE EXCEPTION '找不到訂單編號 %', v_order_number
        USING ERRCODE = 'P0002';
    END IF;
    v_order_ids := array_append(v_order_ids, v_order_id);

    v_result := public.ship_order(
      v_order_id,
      v_shipping_method,
      v_tracking_number,
      NULL
    );
    IF COALESCE((v_result->>'success')::boolean, false) IS NOT TRUE THEN
      RAISE EXCEPTION '訂單 % 出貨未成功', v_order_number
        USING ERRCODE = '55000';
    END IF;
    v_results := v_results || jsonb_build_array(jsonb_build_object(
      'order_number', v_order_number,
      'shipment', v_result->'shipment'
    ));
  END LOOP;

  RETURN jsonb_build_object(
    'shipments', v_results,
    'order_ids', to_jsonb(v_order_ids)
  );
END;
$function$;

REVOKE ALL ON FUNCTION public.bulk_ship_orders(jsonb)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.bulk_ship_orders(jsonb) TO service_role;

